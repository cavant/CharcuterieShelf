import assert from 'node:assert/strict';
import { test, describe } from 'node:test';
import fs from 'node:fs';
import path from 'node:path';

describe('Nuxt Static Bundle & Route Generation Health', () => {
  const distDir = path.resolve('dist');

  test('Static distribution directory exists', () => {
    assert.ok(fs.existsSync(distDir), 'dist/ directory must exist (run npm run generate first)');
  });

  test('Core fallback and entry HTML documents are present', () => {
    const indexHtml = path.join(distDir, 'index.html');
    const fallbackHtml = path.join(distDir, '200.html');

    assert.ok(fs.existsSync(indexHtml), 'dist/index.html must exist');
    assert.ok(fs.existsSync(fallbackHtml), 'dist/200.html client-side fallback must exist');

    const indexContent = fs.readFileSync(indexHtml, 'utf8');
    assert.ok(indexContent.includes('<!doctype html>') || indexContent.includes('<!DOCTYPE html>'));
    assert.ok(indexContent.includes('<div id="__nuxt">'));
  });

  test('Key application routes are pre-rendered into static bundle', () => {
    const requiredRoutes = [
      'bookshelf/index.html',
      'bookshelf/favorites/index.html',
      'bookshelf/latest/index.html',
      'downloading/index.html',
      'settings/index.html',
      'connect/index.html'
    ];

    for (const route of requiredRoutes) {
      const fullPath = path.join(distDir, route);
      assert.ok(
        fs.existsSync(fullPath),
        `Route file "dist/${route}" must be generated by nuxt generate`
      );

      const html = fs.readFileSync(fullPath, 'utf8');
      assert.ok(html.length > 500, `dist/${route} must contain rendered markup`);
    }
  });
});
